"""v1.7 r001: the line's carry-in text fixes, and the default calendar stops
calling itself Gregorian (the cheap half of the review's Pipes item 5).

Version literals. The HTML export's two (the generator meta tag and the
footer line) read v1.7, as the version bump requires.

The default calendar. DEFAULT_CALENDAR (06_calendar-engine) was named
Gregorian, but it has a 28-day February and no leap rule, and Kalendarium has
no leap rules to give it. It becomes Common Year, the name for a 365-day year
without a leap day (Drak, 2026-10-24). Worlds saved before keep the name they
stored (Drak's call: a load-time rewrite of stored user data, the reason
entry-ref flag 6 was skipped). With it:
- the calendar-name placeholder stops suggesting Gregorian, Julian, Islamic,
  and Hebrew, none of which Kalendarium can express;
- Settings' fallback for a calendar with no name reads "(unnamed)", as
  Kalendarium's own row does, instead of naming the default;
- the Kalendarium help and the site's Kalendarium page say what the default
  is, and the schema's worked example (help and site) uses the new name.

The roadmap's three product-text defects:
- Concordance's help says the template filter comes back all-on after a
  reload. Since v1.5's r134 it opens empty, by design, every time the view
  opens. The site's Concordance page says the same thing and gets the same
  fix.
- The in-app JSON Save File Schema topic omits the longform and grid field
  types and their value shapes; the site lists grid as a two-dimensional
  array, which it isn't. Both now give the shape makeEmptyGrid
  (05_field-system) writes, and longform's form-feed divider.
- A promoted Ephemeris event writes "native recurrence support is not in
  v1.5" into its notes (12_trunk). The note drops the version. Entries
  already promoted keep what they were given.

Five more found while reading for this cut, folded in (Drak, 2026-10-24):
- The site says Longform fields are top-level only. The builder offers
  Longform as a subfield at every depth (subfieldTypesAtDepth excludes only
  grid, and group at the last depth), so the text is what's wrong.
- The Field Types help says grid cells hold text, numbers, or entry
  references; GRID_CELL_TYPES also has a calendar date and a date range, and
  each cell picks its own type.
- The Field Types help points at "Calendars & Dates", a topic that doesn't
  exist; it's Kalendarium.
- Cartographia's help says custom per-map field sets are "not part of v1.6",
  stale the day v1.7 ships.
- The schema topic says per-field calendar overrides aren't supported "in
  v1.4", stale since v1.5.
And one found after Drak's first pass, added at his call the same evening:
- The template builder's hint under a Grid field lists four cell types and
  leaves out the calendar date range.

Declared scope: 06_calendar-engine, 08_export-layer, 12_trunk,
15_template-builder, 16_trunk, 26_home-data; site/helloworld.html outside the
tree. No declaration added or removed.

String-anchored edits; every anchor must occur exactly once. Run from
anywhere inside the repository:  python3 inlining/cuts/v1.7_r001_text_fixes.py
"""
