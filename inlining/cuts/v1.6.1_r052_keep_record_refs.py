"""v1.6.1 r052: a reference to an astronomical body or a Glossopoeia record
survives the load (the v1.6.1 patch; Drak's call, 2026-10-23).

migrate() runs on every load, every JSON import, and every snapshot restore.
Near its end, the v1.3 cleanup checks each value of every entry-ref field that
has a list of allowed targets (refTemplatesId) or reference filters, and keeps
a value only if it is the id of an entry in state.entries whose template is
allowed. Since v1.5, bodies (state.celestialBodies) and Glossopoeia records
(state.glossopoeia) are valid targets that are not entries, so the entry lookup
missed them and every such reference was dropped without a word: a Location's
Parent set to a planet, a Historical Event's Location set to a body, and any
user-built multi-template field aimed at a body or a Glossopoeia record. The
app then saved the emptied value back. Shown headless in the shipped v1.5 and
v1.6 finals. Single-target fields never went through the cleanup and kept
their values.

The fix is the rule the picker already offers these records by
(14_form-engine-edit.jsx, EntryRefEditor): a registered record is a valid
target when its source is among the field's targets, refTemplatesId when that
list is set and refTemplateId otherwise, and reference filters don't apply to
it. The lookup is the registry's own list, getRegisteredGraphNodes, the helper
migrate() already calls to keep Concordance positions for the same records
(the v1.5 r131 fix for the same class of bug). Entry references are judged
exactly as before: a missing entry, an entry of a template the field doesn't
allow, or one that fails a filter is still dropped.

Also flips the HTML export's two version literals (the generator meta tag and
the footer line) to v1.6.1, as the version bump requires.

Declared scope: 10_migrate.jsx (the cleanup) and 08_export-layer.jsx (the two
literals). No declaration added or removed: the new lookup is a local inside
migrate().

String-anchored edits; every anchor must occur exactly once. Run from
anywhere inside the repository:  python3 inlining/cuts/v1.6.1_r052_keep_record_refs.py
"""
from pathlib import Path

ROOT = next(p for p in Path(__file__).resolve().parents if (p / 'cartulary-src').is_dir())
MIGRATE = ROOT / "cartulary-src/modules/10_migrate.jsx"
EXPORT = ROOT / "cartulary-src/modules/08_export-layer.jsx"


def edit(path, pairs):
    text = path.read_text(encoding="utf-8")
    for old, new in pairs:
        n = text.count(old)
        assert n == 1, f"{path.name}: anchor occurs {n} times, not once:\n{old[:160]}"
        text = text.replace(old, new)
    path.write_text(text, encoding="utf-8")


edit(MIGRATE, [
    (
        """  // the target's filter-field value is in allowedValues. Invalid refs are
  // silently dropped. Defensive against hand-edited JSON, deleted target
  // entries, and version-skewed worlds.
  const entryById = Object.fromEntries(state.entries.map(e => [e.id, e]));
""",
        """  // the target's filter-field value is in allowedValues. Invalid refs are
  // silently dropped. Defensive against hand-edited JSON, deleted target
  // entries, and version-skewed worlds.
  //
  // v1.6.1 r052: astronomical bodies and Glossopoeia records are valid targets
  // that aren't entries. Until this cut the entry lookup missed them, so every
  // reference to one was dropped here on each load, import, and restore (v1.5
  // and v1.6). A registered record now counts when its source is among the
  // field's targets, the rule the picker offers it by; refFilters don't apply
  // to it, as in the picker. Entry references are judged as before.
  const entryById = Object.fromEntries(state.entries.map(e => [e.id, e]));
  const registeredSourceById = new Map(getRegisteredGraphNodes(state).map(n => [n.id, n.templateId]));
""",
    ),
    (
        """      const isValid = (refId) => {
        if (!refId) return false;
        const target = entryById[refId];
        if (!target) return false;
""",
        """      const isValid = (refId) => {
        if (!refId) return false;
        const target = entryById[refId];
        if (!target) {
          const sourceId = registeredSourceById.get(refId);
          if (!sourceId) return false;
          const allowed = (Array.isArray(f.refTemplatesId) && f.refTemplatesId.length > 0)
            ? f.refTemplatesId
            : (f.refTemplateId ? [f.refTemplateId] : []);
          return allowed.includes(sourceId);
        }
""",
    ),
])

edit(EXPORT, [
    ('<meta name="generator" content="Cartulary v1.6">', '<meta name="generator" content="Cartulary v1.6.1">'),
    ("Generated by Cartulary v1.6 &middot;", "Generated by Cartulary v1.6.1 &middot;"),
])

print("v1.6.1 r052 applied: 10_migrate.jsx (cleanup keeps registered records), 08_export-layer.jsx (v1.6.1 literals)")
